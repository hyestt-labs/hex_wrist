import AppKit
import CryptoKit
import Foundation

/// Saves and restores the whole general pasteboard (every item, every type), so
/// the verify script can use the clipboard as a test sentinel without losing
/// what the person had on it.
///
///   pasteboard-tool save <dir>     exit 0 saved; 3 a concealed item is on the clipboard; 4 some type could not be read.
///                                  On 3 and 4 nothing is written: there is never a partial backup.
///   pasteboard-tool restore <dir>  put the saved items back
///   pasteboard-tool verify <dir>   exit 0 when every saved type is on the clipboard with the same bytes
///   pasteboard-tool set <text>     put one plain string on the clipboard
///   pasteboard-tool get            print the clipboard's plain string
struct SavedType: Codable { let type: String; let file: String; let sha256: String }
struct Saved: Codable { var items: [[SavedType]] }

let concealed: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                              "org.nspasteboard.AutoGeneratedType"]

func sha(_ data: Data) -> String { SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined() }

func fail(_ message: String, _ code: Int32 = 1) -> Never {
    FileHandle.standardError.write(Data((message + "\n").utf8))
    exit(code)
}

let args = Array(CommandLine.arguments.dropFirst())
let board = NSPasteboard.general
guard let command = args.first else { fail("usage: pasteboard-tool save|restore|verify <dir> | set <text> | get", 2) }

func manifestURL(_ dir: String) -> URL { URL(fileURLWithPath: dir).appendingPathComponent("manifest.json") }

switch command {
case "save":
    guard args.count == 2 else { fail("save <dir>", 2) }
    let dir = URL(fileURLWithPath: args[1])
    var saved = Saved(items: [])
    var pending: [(URL, Data)] = []
    var unreadable: [String] = []
    for (i, item) in (board.pasteboardItems ?? []).enumerated() {
        if item.types.contains(where: { concealed.contains($0.rawValue) }) {
            fail("the clipboard holds a concealed or transient item (a password manager?); nothing was saved", 3)
        }
        var types: [SavedType] = []
        for (j, type) in item.types.enumerated() {
            guard let data = item.data(forType: type) else {
                unreadable.append("item \(i): \(type.rawValue)")   // counted and reported, never skipped silently
                continue
            }
            let file = "\(i)-\(j).bin"
            pending.append((dir.appendingPathComponent(file), data))
            types.append(SavedType(type: type.rawValue, file: file, sha256: sha(data)))
        }
        saved.items.append(types)
    }
    if !unreadable.isEmpty {
        fail("\(unreadable.count) clipboard type(s) could not be read, so no backup was made: " + unreadable.joined(separator: "; "), 4)
    }
    try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true,
                                            attributes: [.posixPermissions: 0o700])
    for (url, data) in pending {
        try data.write(to: url, options: .atomic)
        try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
    }
    try JSONEncoder().encode(saved).write(to: manifestURL(args[1]), options: .atomic)
    print("saved \(saved.items.count) item(s), \(pending.count) type(s)")

case "restore":
    guard args.count == 2, let data = try? Data(contentsOf: manifestURL(args[1])),
          let saved = try? JSONDecoder().decode(Saved.self, from: data) else { fail("restore <dir>: no saved clipboard there", 2) }
    var items: [NSPasteboardItem] = []
    for types in saved.items {
        let item = NSPasteboardItem()
        for t in types {
            guard let bytes = try? Data(contentsOf: URL(fileURLWithPath: args[1]).appendingPathComponent(t.file)) else { continue }
            item.setData(bytes, forType: NSPasteboard.PasteboardType(t.type))
        }
        items.append(item)
    }
    board.clearContents()
    if !items.isEmpty, !board.writeObjects(items) { fail("could not write the saved items back") }
    print("restored \(items.count) item(s)")

case "verify":
    guard args.count == 2, let data = try? Data(contentsOf: manifestURL(args[1])),
          let saved = try? JSONDecoder().decode(Saved.self, from: data) else { fail("verify <dir>", 2) }
    let current = board.pasteboardItems ?? []
    var problems: [String] = []
    if current.count != saved.items.count { problems.append("items: \(current.count) now, \(saved.items.count) saved") }
    for (i, types) in saved.items.enumerated() where i < current.count {
        for t in types {
            guard let now = current[i].data(forType: NSPasteboard.PasteboardType(t.type)) else {
                problems.append("item \(i) lost \(t.type)"); continue
            }
            if sha(now) != t.sha256 { problems.append("item \(i) \(t.type) bytes differ") }
        }
    }
    if problems.isEmpty { print("clipboard matches the saved copy"); exit(0) }
    fail(problems.joined(separator: "; "), 1)

case "set":
    guard args.count == 2 else { fail("set <text>", 2) }
    board.clearContents()
    board.setString(args[1], forType: .string)

case "get":
    print(board.string(forType: .string) ?? "", terminator: "")

default:
    fail("unknown command \(command)", 2)
}
