#!/usr/bin/env python3
"""Generate src/transcription/model_benchmarks/catalog.rs from transcribe.cpp's catalog.

    python3 -I scripts/models/catalog-records.py [CHECKOUT]

CHECKOUT is a transcribe.cpp checkout at the revision Hex pins (Cargo.toml's
`transcribe-cpp` rev; default: the Cargo git checkout of it). The script
refuses any other revision, keeps only Unit F's five models, and writes the
same file for the same input, so a reviewer can rerun it and diff.

Accuracy: FLEURS test, Q8_0, batch 8, no timestamps, one record per language
that Settings lists (src/transcription/languages.rs) and the model supports.
Speed: Q8_0 on both samples (jfk, dots) for every reference machine; xrt_wall.
"""
import json
import pathlib
import re
import subprocess
import sys

PINNED = "2778ae4"
MODELS = [
    # (catalog file, Rust id, constant prefix)
    ("whisper-large-v3", "WhisperLargeV3", "WHISPER_LARGE_V3"),
    ("whisper-medium", "WhisperMedium", "WHISPER_MEDIUM"),
    ("whisper-small", "WhisperSmall", "WHISPER_SMALL"),
    ("breeze-asr-25", "BreezeAsr25", "BREEZE_ASR_25"),
    ("qwen3-asr-1.7b", "Qwen3Asr17B", "QWEN_1_7B"),
]
MACHINES = {"m4-max": "Apple M4 Max", "m4": "Apple M4", "ryzen-4750u": "AMD Ryzen 7 PRO 4750U"}
BACKENDS = {"metal": "Metal", "vulkan": "Vulkan", "cpu": "Cpu"}
SAMPLES = {"jfk": "JFK", "dots": "DOTS"}

root = pathlib.Path(__file__).resolve().parent.parent.parent
default = next(
    (pathlib.Path.home() / ".cargo/git/checkouts").glob("transcribe.cpp-*/" + PINNED + "*"), None
)
checkout = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else default
if checkout is None or not (checkout / "catalog").is_dir():
    sys.exit("pass a transcribe.cpp checkout at " + PINNED)
head = subprocess.run(
    ["git", "-C", str(checkout), "rev-parse", "HEAD"], capture_output=True, text=True, check=True
).stdout.strip()
if not head.startswith(PINNED):
    sys.exit(f"the checkout is at {head[:7]}, Hex pins {PINNED}")

# Only the list Settings offers (`LANGUAGES`), not the names-only table after it.
_source = (root / "src/transcription/languages.rs").read_text()
_block = _source.split("pub const LANGUAGES", 1)[1].split("\n];", 1)[0]
languages = re.findall(r'\("([a-z]+)", "', _block)
order = {code: index for index, code in enumerate(languages)}


def num(value):
    text = repr(float(value))
    return text


def accuracy(entry):
    rows = [
        row
        for row in entry["accuracy_benchmarks"]
        if row["dataset"] == "fleurs"
        and row["split"] == "test"
        and row["quant"] == "Q8_0"
        and row["batch_size"] == 8
        and row["timestamps"] == "none"
        and row["language"] in order
        and row["language"] != "auto"
    ]
    seen = set()
    for row in rows:
        assert row["language"] not in seen, f"two records for {row['language']}"
        assert row.get("measurement_provenance") == "legacy-published", row
        assert row["engine_sha"] is None and row["measured_on"] is None, row
        seen.add(row["language"])
    rows.sort(key=lambda row: order[row["language"]])
    lines = []
    for row in rows:
        low, high = row["ci95"]
        assert low is not None and high is not None, row
        metric = {"wer": "Wer", "cer": "Cer"}[row["metric"]]
        lines.append(
            f'    fleurs({metric}, {num(row["err_pct"])}, "{row["language"]}", '
            f'({num(low)}, {num(high)}), {row["n_utts"]}),'
        )
    return lines


def speed(entry, machines):
    rows = [row for row in entry["speed_benchmarks"] if row["quant"] == "Q8_0"]
    seen = set()
    lines = []
    for row in sorted(rows, key=lambda r: (r["machine"], r["backend"], r["sample"])):
        key = (row["machine"], row["backend"], row["sample"])
        assert key not in seen, key
        seen.add(key)
        machine = (row["machine"], row["engine_sha"], row["measured_on"])
        machines.add(machine)
        name = machine_const(machine)
        lines.append(
            f'    measured(Backend::{BACKENDS[row["backend"]]}, &{name}, '
            f'{SAMPLES[row["sample"]]}, {num(row["xrt_wall"])}),'
        )
        assert abs(row["sample_duration_s"] - {"jfk": 11.0, "dots": 35.332}[row["sample"]]) < 1e-9
    return lines


def machine_const(machine):
    name, sha, _ = machine
    return name.upper().replace("-", "_") + "_" + sha.upper()


out = [
    f"//! Unit F's catalog records, generated by `scripts/models/catalog-records.py`",
    f"//! from transcribe.cpp {PINNED}'s catalog. Do not edit by hand.",
    "",
    "// Catalog values are data: 6.28 is a word error rate, not tau.",
    "#![allow(clippy::approx_constant)]",
    "// The speed records wait for the picker's UI unit.",
    "#![cfg_attr(not(test), allow(dead_code))]",
    "",
    "use super::{Backend, BenchmarkRecord, ErrorMetric, Machine, SpeedRecord};",
    "use crate::transcription::models::TranscriptionModelId;",
    "use ErrorMetric::{Cer, Wer};",
    "",
    f'const SOURCE: &str = "transcribe.cpp catalog, legacy-published";',
    f'const REVISION: &str = "{PINNED}";',
    "",
    "/// FLEURS test, Q8_0, batch 8, no timestamps, scored over every utterance;",
    "/// the engine revision and date are null in the catalog, and the hardware is a",
    "/// profile setting, not a recorded fact.",
    "const fn fleurs(",
    "    metric: ErrorMetric,",
    "    value: f64,",
    "    language: &'static str,",
    "    ci95: (f64, f64),",
    "    utterances: u32,",
    ") -> BenchmarkRecord {",
    "    BenchmarkRecord {",
    "        metric,",
    "        value,",
    "        language,",
    '        dataset: Some("FLEURS test"),',
    "        source: Some(SOURCE),",
    "        source_revision: Some(REVISION),",
    "        utterances: Some(utterances),",
    "        batch_size: Some(8),",
    "        timestamps: Some(false),",
    "        hardware: None,",
    '        quantization: Some("Q8_0"),',
    "        ci95: Some(ci95),",
    "    }",
    "}",
    "",
    "const fn measured(",
    "    backend: Backend,",
    "    machine: &'static Machine,",
    "    sample: (&'static str, f64),",
    "    realtime: f64,",
    ") -> SpeedRecord {",
    "    SpeedRecord {",
    "        backend,",
    "        machine: machine.name,",
    "        sample: sample.0,",
    "        sample_seconds: sample.1,",
    "        realtime,",
    "        engine_revision: machine.engine_revision,",
    "        measured_on: machine.measured_on,",
    "    }",
    "}",
    "",
    'const JFK: (&str, f64) = ("jfk", 11.0);',
    'const DOTS: (&str, f64) = ("dots", 35.332);',
    "",
]

blocks = []
machines = set()
for catalog_name, rust_id, prefix in MODELS:
    entry = json.loads((checkout / "catalog" / f"{catalog_name}.json").read_text())
    assert entry["variant"] == catalog_name, entry["variant"]
    acc = accuracy(entry)
    spd = speed(entry, machines)
    assert acc and spd
    blocks.append((rust_id, prefix, acc, spd))

for machine in sorted(machines):
    name, sha, date = machine
    out += [
        f"const {machine_const(machine)}: Machine = Machine {{",
        f'    name: "{MACHINES[name]}",',
        f'    engine_revision: "{sha}",',
        f'    measured_on: "{date}",',
        "};",
    ]
out.append("")
for rust_id, prefix, acc, spd in blocks:
    out.append(f"const {prefix}_ACCURACY: &[BenchmarkRecord] = &[")
    out += acc
    out += ["];", f"const {prefix}_SPEED: &[SpeedRecord] = &["]
    out += spd
    out += ["];", ""]
for fn, suffix in (("accuracy", "ACCURACY"), ("speed", "SPEED")):
    kind = "BenchmarkRecord" if fn == "accuracy" else "SpeedRecord"
    out.append(f"pub(super) fn {fn}_of(id: TranscriptionModelId) -> &'static [{kind}] {{")
    out.append("    match id {")
    for rust_id, prefix, _, _ in blocks:
        out.append(f"        TranscriptionModelId::{rust_id} => {prefix}_{suffix},")
    out.append("        _ => &[],")
    out += ["    }", "}", ""]

target = root / "src/transcription/model_benchmarks/catalog.rs"
target.write_text("\n".join(out).rstrip("\n") + "\n")
print(f"wrote {target.relative_to(root)}: {sum(len(b[2]) for b in blocks)} accuracy and "
      f"{sum(len(b[3]) for b in blocks)} speed records from {head[:7]}")
